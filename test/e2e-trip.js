const { chromium, devices } = require('playwright');
const fs = require('fs'), path = require('path');
const APP = 'http://localhost:8080/', API = 'http://localhost:8090/exec';
const key = fs.readFileSync(path.join(__dirname, '.key'), 'utf8');
const ctl = async q => (await fetch('http://localhost:8090/__ctl?' + q)).json();
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const hash = '#setup=' + Buffer.from(JSON.stringify({ url: API, key })).toString('base64');
(async () => {
  const b = await chromium.launch(); const phone = { ...devices['iPhone 13'] }; delete phone.defaultBrowserType;
  const ctx = await b.newContext({ ...phone, deviceScaleFactor: 2 }); const p = await ctx.newPage();
  p.on('dialog', d => d.accept()); p.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  await p.goto(APP + hash); await p.waitForSelector('.group');
  const sheetQty = async n => { const st = await ctl(''); const h = st.grid[0]; return st.grid.find(r => r[0] === n)[h.indexOf('Cant')]; };
  const appQty = n => p.evaluate(n => { const S = window.__sva.S; const o = {}; S.outbox.forEach(c => { if (c.field === 'qty') o[c.id] = c.value; });
    const it = S.items.find(i => i.eng === n); return it.id in o ? o[it.id] : it.qty; }, n);
  // check one item first, to confirm checks get cleared
  await p.locator('.item', { hasText: 'bananas' }).locator('[data-act=check]').click();
  await p.click('[data-act=new-list]');
  await p.waitForSelector('#trip[open]');
  const hint = await p.textContent('#trip .meta');
  ok(/^2\d items/.test(hint), 'dialog explains count: ' + hint.slice(0, 40));
  await p.screenshot({ path: path.join(__dirname, 'shots', 'trip-dialog.png') });
  await p.click('#trip [data-days="2"]');
  ok(await appQty('tomatoes (big 1, small x2)') === 8, '2 days: tomatoes 4/day -> 8');
  ok(await appQty('grenadine') === 1, '2 days: grenadine 0.5/day -> 1');
  ok(await appQty('chicken tour') === 4, '2 days: chicken 2/day -> 4');
  ok(await appQty('vinegar') === 1, 'vinegar (no daily value) unchanged');
  ok(await p.locator('.item.done').count() === 0, 'check-marks cleared');
  ok((await p.textContent('#toast')).includes('2 days'), 'toast: ' + await p.textContent('#toast'));
  await p.evaluate(() => window.__sva.sync(true));
  ok(await sheetQty('tomatoes (big 1, small x2)') === 8 && await sheetQty('cucumber') === 8, 'synced to sheet (tomatoes 8, cucumber 8)');
  await p.click('[data-act=new-list]'); await p.click('#trip [data-days="1"]');
  ok(await appQty('tomatoes (big 1, small x2)') === 4 && await appQty('grenadine') === 1 && await appQty('plates') === 2, '1 day: tomatoes 4, grenadine 1 (rounded up), plates 2');
  ok(await appQty('bread - fish') === 1, 'bread - fish (0.5/day, was empty) now 1 -> added to list');
  await p.evaluate(() => window.__sva.sync(true));
  ok(await sheetQty('tomatoes (big 1, small x2)') === 4, 'synced 1-day list to sheet');
  await p.click('[data-lang=es]'); await p.click('[data-act=new-list]');
  ok((await p.textContent('#trip')).includes('2 días') && (await p.textContent('#trip')).includes('Última lista'), 'Spanish dialog + last list shown');
  await p.screenshot({ path: path.join(__dirname, 'shots', 'trip-dialog-es.png') });
  await p.click('#trip [data-act=close]'); await p.click('[data-lang=en]');
  await p.evaluate(() => window.scrollTo(0, 0)); await p.screenshot({ path: path.join(__dirname, 'shots', 'trip-shop.png') });
  await b.close(); console.log(fails ? fails + ' FAILED' : 'ALL PASSED'); process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
