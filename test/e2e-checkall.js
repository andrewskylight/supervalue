const { chromium, devices } = require('playwright');
const fs = require('fs'), path = require('path');
const APP = 'http://localhost:8080/', API = 'http://localhost:8090/exec';
const key = fs.readFileSync(path.join(__dirname, '.key'), 'utf8');
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const b = await chromium.launch(); const phone = { ...devices['iPhone 13'] }; delete phone.defaultBrowserType;
  const p = await (await b.newContext({ ...phone, deviceScaleFactor: 2 })).newPage();
  p.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  await p.goto(APP + '#setup=' + Buffer.from(JSON.stringify({ url: API, key })).toString('base64'));
  await p.waitForSelector('.group');
  const g = () => p.locator('.group', { has: p.locator('h2', { hasText: /^Isle 9/ }) });
  const n = await g().locator('.item').count();
  ok((await g().locator('.checkall').textContent()) === 'Check all', 'Isle 9 has a Check all button (' + n + ' items)');
  const otherBefore = await p.locator('.item.done').count();
  await g().locator('.checkall').click();
  ok(await g().locator('.item.done').count() === n, 'all ' + n + ' items in Isle 9 checked');
  ok(await p.locator('.item.done').count() === otherBefore + n, 'other isles untouched');
  ok((await g().locator('.count').textContent()) === '0', 'count shows 0 left');
  ok((await g().locator('.subhead').textContent()).includes(String(n)), 'items moved to Checked sub-section');
  ok((await g().locator('.checkall').textContent()) === 'Uncheck all', 'button turns into Uncheck all');
  await p.locator('.group', { has: p.locator('h2', { hasText: /^Isle 9/ }) }).scrollIntoViewIfNeeded();
  await p.screenshot({ path: path.join(__dirname, 'shots', 'checkall.png') });
  await p.reload(); await p.waitForSelector('.group');
  ok(await g().locator('.item.done').count() === n, 'checks survive reload');
  await g().locator('.checkall').click();
  ok(await g().locator('.item.done').count() === 0, 'Uncheck all clears them');
  await p.click('[data-lang=es]');
  ok((await p.locator('.group', { has: p.locator('h2', { hasText: /^Pasillo 9/ }) }).locator('.checkall').textContent()) === 'Marcar todo', 'Spanish: Marcar todo');
  await b.close(); console.log(fails ? fails + ' FAILED' : 'ALL PASSED'); process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
